function baseName(name) {
  return name
    .replace(/\s+(большой|б|м|Б)$/iu, "")
    .replace(/\s+большой$/iu, "")
    .trim();
}

function lookupDescription(name) {
  if (DESCRIPTIONS[name]) return DESCRIPTIONS[name];
  const base = baseName(name);
  if (DESCRIPTIONS[base]) return DESCRIPTIONS[base];

  const lower = name.toLowerCase();
  const baseLower = baseName(lower);
  for (const [key, value] of Object.entries(DESCRIPTIONS)) {
    if (key.toLowerCase() === lower || key.toLowerCase() === baseLower) {
      return value;
    }
  }
  return null;
}

async function main() {
  const menus = JSON.parse(await readFile(MENUS_FILE, "utf8"));
  let updated = 0;
  const stillMissing = new Set();

  for (const franchiseId of Object.keys(menus)) {
    for (const item of menus[franchiseId]) {
      const desc = lookupDescription(item.name);
      if (desc) {
        item.description = desc;
        updated++;
      } else if (item.description === "Состав уточняется") {
        stillMissing.add(item.name);
      }
    }
  }

  await writeFile(MENUS_FILE, JSON.stringify(menus, null, 2) + "\n", "utf8");
  console.log(`Обновлено описаний: ${updated}`);
  if (stillMissing.size) {
    console.log(`Без состава (${stillMissing.size}):`, [...stillMissing].sort().join(", "));
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
